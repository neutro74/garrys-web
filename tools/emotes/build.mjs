#!/usr/bin/env node
// Builds the emoji and sticker lists the chat picker (web/emote-picker.js) shows:
//  - web/emotes/unicode.js: every emoji-presentation Unicode character with its name, grouped by Unicode block
//    (names come from Python's unicodedata, which tracks the Unicode version);
//  - web/emotes/packs.js: GMod's own art from the game install: Silkicons (materials/icon16) and flags (materials/flags16)
//    as emojis; the spawn-menu entity pictures (materials/entities) and a hand-picked set of prop spawn icons as stickers.
// The images themselves are the game's stock files, loaded from the package like the rest of the game; nothing is copied.
//   node tools/emotes/build.mjs   (needs the game install: dist/gmod-web/asset)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const asset = process.env.GMOD_ASSET ?? path.join(repo, 'dist/gmod-web/asset/garrysmod');
const out = path.join(repo, 'web/emotes');
fs.mkdirSync(out, { recursive: true });

// ---- Unicode ----
const BLOCKS = [
  ['Smileys', 0x1f600, 0x1f64f], ['People & more', 0x1f900, 0x1f9ff], ['Nature & objects', 0x1f300, 0x1f5ff],
  ['Travel & places', 0x1f680, 0x1f6ff], ['New', 0x1fa70, 0x1faff], ['Symbols', 0x2600, 0x27bf],
];
const cps = [];
for (const [, a, b] of BLOCKS) for (let cp = a; cp <= b; cp++) if (/^\p{Emoji_Presentation}$/u.test(String.fromCodePoint(cp))) cps.push(cp);
const names = JSON.parse(execFileSync('python3', ['-I', '-c', 'import sys,json,unicodedata;print(json.dumps([unicodedata.name(chr(c),"") for c in json.load(sys.stdin)]))'], { input: JSON.stringify(cps) }));
const byCp = new Map(cps.map((c, i) => [c, names[i].toLowerCase()]));
const groups = BLOCKS.map(([title, a, b]) => [title, cps.filter((c) => c >= a && c <= b && byCp.get(c)).map((c) => [String.fromCodePoint(c), byCp.get(c)])]);
fs.writeFileSync(path.join(out, 'unicode.js'), `// Generated by tools/emotes/build.mjs: [group, [[emoji, name], ...]]\nexport const UNICODE = ${JSON.stringify(groups)};\n`);

// ---- GMod art ----
const list = (dir) => fs.readdirSync(path.join(asset, dir)).filter((f) => f.endsWith('.png')).map((f) => f.slice(0, -4)).sort();
// Well-known props, by spawn icon path (models/<path>.png); those missing from this install are left out.
const PROPS = {
  melon: 'props_junk/watermelon01', barrel: 'props_c17/oildrum001', explosive_barrel: 'props_c17/oildrum001_explosive',
  gas_can: 'props_junk/gascan001a', propane: 'props_junk/propane_tank001a', crate: 'props_junk/wood_crate001a',
  crate_big: 'props_junk/wood_crate002a', cardboard_box: 'props_junk/cardboard_box001a', bathtub: 'props_interiors/bathtub01a',
  sofa: 'props_c17/furniturecouch001a', fridge: 'props_c17/furniturefridge001a', blastdoor: 'props_lab/blastdoor001c',
  dumpster: 'props_junk/trashdumpster01a', tire: 'props_vehicles/carparts_tire01a', wheel: 'props_vehicles/carparts_wheel01a',
  car: 'props_vehicles/car002a_physics', van: 'props_vehicles/van001a_physics', trashbin: 'props_junk/trashbin01a',
  traffic_cone: 'props_junk/trafficcone001a', sawblade: 'props_junk/sawblade001a', harpoon: 'props_junk/harpoon002a',
  radiator: 'props_interiors/radiator01a', vending_machine: 'props_interiors/vendingmachinesoda01a', clock: 'props_c17/clock01',
  doll: 'props_c17/doll01', bugbait: 'props_lab/huladoll', monitor: 'props_lab/monitor01a', tv: 'props_c17/tv_monitor01',
  lamp: 'props_interiors/furniture_lamp01a', chair: 'props_c17/chair02a', bench: 'props_c17/bench01a', ladder: 'props_c17/metalladder001',
  shopping_cart: 'props_junk/pushcart01a', bucket: 'props_junk/metalbucket01a', pot: 'props_c17/metalpot001a', bottle: 'props_junk/garbage_glassbottle001a',
  coffee: 'props_junk/garbage_coffeemug001a', paint_can: 'props_junk/metal_paintcan001a', shoe: 'props_junk/shoe001a', baby_doll: 'props_c17/doll01',
  phx_ball: 'props_phx/misc/soccerball', phx_wheel: 'props_phx/wheels/drugster_front', rocket: 'props_phx/rocket1', bomb: 'props_phx/torpedo',
  hula: 'props_lab/huladoll', skull: 'gibs/hgibs', antlion: 'antlion', headcrab: 'headcrabclassic', kleiner: 'kleiner', alyx: 'alyx',
  gman: 'gman_high', dog: 'dog', zombie: 'zombie/classic', combine: 'combine_soldier', metrocop: 'police', vortigaunt: 'vortigaunt', barney: 'barney',
};
const props = Object.entries(PROPS).filter(([, p]) => fs.existsSync(path.join(asset, 'materials/spawnicons/models', p + '.png')));
const packs = {
  silk: list('materials/icon16'),
  flags: list('materials/flags16'),
  entities: list('materials/entities'),
  props: Object.fromEntries(props),
};
fs.writeFileSync(path.join(out, 'packs.js'), `// Generated by tools/emotes/build.mjs from the game install (stock art; the files load from the package).\nexport const PACKS = ${JSON.stringify(packs)};\n`);
console.log(`unicode ${cps.length}, silk ${packs.silk.length}, flags ${packs.flags.length}, entities ${packs.entities.length}, props ${props.length}/${Object.keys(PROPS).length}`);
console.log('missing props:', Object.entries(PROPS).filter(([k]) => !packs.props[k]).map(([k, p]) => `${k}=${p}`).join(' '));
