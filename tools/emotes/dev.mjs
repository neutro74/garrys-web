#!/usr/bin/env node
// The "Dev & apps" emoji set: editor, language, OS, browser and engine logos from Devicon (MIT licence,
// github.com/devicons/devicon), drawn to 128 px PNGs in web/emotes/dev/ with their list in web/emotes/dev.js.
//   node tools/emotes/dev.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createCanvas, loadImage } from '@napi-rs/canvas';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'), dir = path.join(repo, 'web/emotes/dev'), V = '2.16.0';
// emoji name: devicon name (all use the "original" coloured version)
const SETS = {
  'Editors & tools': { vscode: 'vscode', visualstudio: 'visualstudio', vim: 'vim', neovim: 'neovim', intellij: 'intellij', jetbrains: 'jetbrains', git: 'git', github: 'github', gitlab: 'gitlab', docker: 'docker', bash: 'bash', powershell: 'powershell', stackoverflow: 'stackoverflow', figma: 'figma', photoshop: 'photoshop', gimp: 'gimp', blender: 'blender', slack: 'slack', json: 'json', markdown: 'markdown' },
  'Languages': { lua: 'lua', javascript: 'javascript', typescript: 'typescript', python: 'python', rust: 'rust', cpp: 'cplusplus', c: 'c', csharp: 'csharp', java: 'java', go: 'go', php: 'php', ruby: 'ruby', kotlin: 'kotlin', swift: 'swift', html: 'html5', css: 'css3', sass: 'sass', wasm: 'wasm', latex: 'latex' },
  'Systems & browsers': { linux: 'linux', ubuntu: 'ubuntu', debian: 'debian', fedora: 'fedora', archlinux: 'archlinux', windows: 'windows11', apple: 'apple', android: 'android', raspberrypi: 'raspberrypi', chrome: 'chrome', firefox: 'firefox', safari: 'safari', opera: 'opera' },
  'Web & engines': { node: 'nodejs', bun: 'bun', react: 'react', vue: 'vuejs', svelte: 'svelte', electron: 'electron', threejs: 'threejs', jquery: 'jquery', tailwind: 'tailwindcss', bootstrap: 'bootstrap', nginx: 'nginx', cloudflare: 'cloudflare', googlecloud: 'googlecloud', mysql: 'mysql', postgres: 'postgresql', mongodb: 'mongodb', sqlite: 'sqlite', redis: 'redis', unity: 'unity', unreal: 'unrealengine', godot: 'godot' },
};
fs.mkdirSync(dir, { recursive: true });
const got = {};
for (const [set, list] of Object.entries(SETS)) {
  got[set] = [];
  for (const [name, icon] of Object.entries(list)) {
    const r = await fetch(`https://cdn.jsdelivr.net/gh/devicons/devicon@v${V}/icons/${icon}/${icon}-original.svg`);
    if (!r.ok) { console.warn(`missing ${icon}`); continue; }
    const img = await loadImage(Buffer.from(await r.arrayBuffer()));
    const c = createCanvas(128, 128), g = c.getContext('2d'), k = Math.min(116 / img.width, 116 / img.height);
    g.drawImage(img, (128 - img.width * k) / 2, (128 - img.height * k) / 2, img.width * k, img.height * k);
    fs.writeFileSync(path.join(dir, name + '.png'), c.toBuffer('image/png'));
    got[set].push(name);
  }
}
fs.writeFileSync(path.join(repo, 'web/emotes/dev.js'), `// Generated by tools/emotes/dev.mjs: Devicon logos (MIT) in web/emotes/dev/, by set.\nexport const DEV = ${JSON.stringify(got)};\n`);
console.log(Object.entries(got).map(([k, v]) => `${k} ${v.length}`).join(', '));
