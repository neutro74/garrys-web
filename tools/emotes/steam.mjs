#!/usr/bin/env node
// Downloads the Steam emoticons Garry's Web ships (web/emotes/steam/<name>.png) and writes their list (web/emotes/steam.js).
// Not all 69,000 on Steam: Steam's own, and those of Garry's Mod and the games it is built on and mounts.
//   node tools/emotes/steam.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'), dir = path.join(repo, 'web/emotes/steam');
const SETS = {
  'Steam': ['steamhappy', 'steamsad', 'steammocking', 'steamthumbsup', 'steamthumbsdown', 'steamfacepalm', 'steamsalty', 'steamthis', 'steambored', 'steamhearteyes'],
  "Garry's Mod": ['physgun', 'melon', 'box', 'facepunch'],
  'Half-Life 2': ['gordon', 'alyx', 'headcrab', 'eli', 'gman'],
  'Black Mesa': ['bms', 'egon', 'houndeye', 'vort', 'bms_crowbar', 'bms_headcrab'],
  'Portal 2': ['p2aperture', 'p2blue', 'p2orange', 'p2chell', 'p2cube'],
  'Counter-Strike': ['csgoct', 'csgox', 'csgoa', 'csgob', 'csgogun', 'csgohelmet', 'csgocross', 'csgoanarchist', 'csgoskull', 'csgostar'],
  'Day of Defeat': ['alliedstar', 'alliedbridge', 'ironcross', 'axisfountain', 'dodcp'],
  'Left 4 Dead 2': ['boomer', 'tank', 'witch', 'health', 'chainsaw'],
  'Team Fortress 2': ['sentry', 'jarate', 'sticky', 'crate', 'medicon', 'spycon', 'demoticon', 'balloonicorn'],
};
fs.mkdirSync(dir, { recursive: true });
const got = {};
for (const [set, names] of Object.entries(SETS)) {
  got[set] = [];
  for (const n of names) {
    const f = path.join(dir, n.toLowerCase() + '.png');
    if (!fs.existsSync(f)) {
      const r = await fetch(`https://community.akamai.steamstatic.com/economy/emoticonlarge/${n}`);
      if (!r.ok) { console.warn(`missing ${n} (${r.status})`); continue; }
      fs.writeFileSync(f, Buffer.from(await r.arrayBuffer()));
      await new Promise((res) => setTimeout(res, 250));
    }
    got[set].push(n.toLowerCase());
  }
}
fs.writeFileSync(path.join(repo, 'web/emotes/steam.js'), `// Generated by tools/emotes/steam.mjs: the Steam emoticons shipped in web/emotes/steam/, by set.\nexport const STEAM = ${JSON.stringify(got)};\n`);
console.log(Object.entries(got).map(([k, v]) => `${k} ${v.length}`).join(', '));
